"""Base event schemas for multi-domain streaming platform.

Provides domain-agnostic TypedDict definitions and encoder/decoder functions
for base events shared across all pluggable domains. Domain-specific events
extend these base types with additional fields.

Event types:
- BaseInputEventV1: Minimal input event consumed from Kafka.
- BasePredictionEventV1: Minimal prediction event published to Kafka.
- BaseAlertEventV1: Minimal alert event for high-severity predictions.

Strict typing: no Any, no casts, no type: ignore.
"""

from __future__ import annotations

from typing import Literal, TypedDict

from platform_core.json_utils import (
    JSONTypeError,
    dump_json_str,
    load_json_str,
    narrow_json_to_dict,
    require_float,
    require_int,
    require_str,
)

# =============================================================================
# Shared Type Aliases
# =============================================================================

BaseAlertSeverity = Literal["info", "warning", "critical"]

# =============================================================================
# Input Event: BaseInputEventV1
# =============================================================================


class BaseInputEventV1(TypedDict):
    """Minimal input event consumed from Kafka.

    All domain-specific input events must include these fields.
    Domain implementations extend this with additional domain-specific fields.

    Attributes:
        type: Event type discriminator (domain.event_name.version).
        event_id: UUID for deduplication.
        entity_id: Primary entity identifier (deal_id, match_id, station_id).
        timestamp: ISO datetime when event was emitted.
    """

    type: str
    event_id: str
    entity_id: str
    timestamp: str


# =============================================================================
# Output Event: BasePredictionEventV1
# =============================================================================


class BasePredictionEventV1(TypedDict):
    """Minimal prediction event published to Kafka.

    All domain-specific prediction events must include these fields.

    Attributes:
        type: Event type discriminator.
        event_id: UUID for this event.
        entity_id: Primary entity identifier.
        prediction_value: Primary prediction output (probability, score, etc.).
        confidence: Model confidence in prediction (0.0-1.0).
        model_version: Version string of the ML model used.
        latency_ms: Inference latency in milliseconds.
        processed_at: ISO datetime when processing completed.
    """

    type: str
    event_id: str
    entity_id: str
    prediction_value: float
    confidence: float
    model_version: str
    latency_ms: int
    processed_at: str


# =============================================================================
# Output Event: BaseAlertEventV1
# =============================================================================


class BaseAlertEventV1(TypedDict):
    """Minimal alert event for high-severity predictions.

    Published when a prediction exceeds the domain's alert threshold.
    Contains a human-readable summary generated by Gemini.

    Attributes:
        type: Event type discriminator.
        event_id: UUID for this event.
        entity_id: Primary entity identifier.
        alert_type: Category of alert (domain-specific string).
        severity: Alert severity level.
        prediction_value: Value that triggered the alert.
        gemini_summary: Human-readable summary from Gemini.
        triggered_at: ISO datetime when alert was triggered.
    """

    type: str
    event_id: str
    entity_id: str
    alert_type: str
    severity: BaseAlertSeverity
    prediction_value: float
    gemini_summary: str
    triggered_at: str


