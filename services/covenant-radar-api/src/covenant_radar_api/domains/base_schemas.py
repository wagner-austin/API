# =============================================================================
# Literal Type Parsers
# =============================================================================


def _parse_base_alert_severity(raw: str) -> BaseAlertSeverity:
    """Parse base alert severity from string.

    Args:
        raw: Raw string value.

    Returns:
        Validated BaseAlertSeverity literal.

    Raises:
        JSONTypeError: If value is not a valid severity.
    """
    if raw == "info":
        return "info"
    if raw == "warning":
        return "warning"
    if raw == "critical":
        return "critical"
    raise JSONTypeError(f"Invalid base alert severity '{raw}'")


