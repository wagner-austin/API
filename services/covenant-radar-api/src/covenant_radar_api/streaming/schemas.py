def _parse_evaluation_status(raw: str) -> EvaluationStatus:
    """Parse evaluation status from string.

    Args:
        raw: Raw string value.

    Returns:
        Validated EvaluationStatus literal.

    Raises:
        JSONTypeError: If value is not valid.
    """
    if raw == "OK":
        return "OK"
    if raw == "BREACH":
        return "BREACH"
    if raw == "WARNING":
        return "WARNING"
    raise JSONTypeError(f"Invalid evaluation status '{raw}'")


def _parse_risk_tier(raw: str) -> RiskTier:
    """Parse risk tier from string.

    Args:
        raw: Raw string value.

    Returns:
        Validated RiskTier literal.

    Raises:
        JSONTypeError: If value is not valid.
    """
    if raw == "LOW":
        return "LOW"
    if raw == "MEDIUM":
        return "MEDIUM"
    if raw == "HIGH":
        return "HIGH"
    if raw == "CRITICAL":
        return "CRITICAL"
