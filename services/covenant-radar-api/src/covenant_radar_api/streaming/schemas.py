"""Kafka event schemas for streaming pipeline.

This module provides TypedDict definitions and encoder/decoder functions
for Kafka events used in the streaming inference pipeline.

Event types:
- MeasurementEventV1: Input measurement events from Kafka
- PredictionEventV1: Output prediction events to Kafka
- AlertEventV1: High-severity alert events with Gemini text

Strict typing: no Any, no casts, no type: ignore.
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Literal, TypedDict, TypeGuard

from covenant_domain.features import RiskTier, classify_risk_tier
from platform_core.json_utils import (
    JSONObject,
    JSONTypeError,
    dump_json_str,
    load_json_str,
    narrow_json_to_dict,
    require_float,
    require_int,
    require_str,
)

# =============================================================================
# Event Type Discriminators
# =============================================================================

MeasurementEventType = Literal["covenant.measurement.v1"]
PredictionEventType = Literal["covenant.prediction.v1"]
AlertEventType = Literal["covenant.alert.v1"]

KafkaEventType = Literal[
    "covenant.measurement.v1",
    "covenant.prediction.v1",
    "covenant.alert.v1",
]

# =============================================================================
# Shared Type Aliases
# =============================================================================

EvaluationStatus = Literal["OK", "BREACH", "WARNING"]
# RiskTier is imported from covenant_domain.features (single source of truth)
AlertType = Literal["breach", "high_risk"]
AlertSeverity = Literal["warning", "critical"]

# =============================================================================
# Input Event: MeasurementEventV1
# =============================================================================


class MeasurementEventV1(TypedDict):
    """Single measurement event consumed from Kafka.

    This event represents a single metric measurement for a deal during a
    specific period. Multiple measurements are aggregated before evaluation.

    Fields:
        type: Event type discriminator.
        event_id: UUID for deduplication.
        deal_id: Deal identifier (partition key).
        period_start: ISO date (YYYY-MM-DD) for period start.
        period_end: ISO date (YYYY-MM-DD) for period end.
        metric_name: Metric identifier (e.g., "debt_to_equity", "ebitda").
        metric_value: Numeric value of the metric.
        timestamp: ISO datetime when event was emitted.
    """

    type: MeasurementEventType
    event_id: str
    deal_id: str
    period_start: str
    period_end: str
    metric_name: str
    metric_value: float
    timestamp: str


# =============================================================================
# Output Event: PredictionEventV1
# =============================================================================


class PredictionEventV1(TypedDict):
    """Risk prediction event published to Kafka.

    Contains both deterministic covenant evaluation results and ML prediction
    for a deal during a specific period.

    Fields:
        type: Event type discriminator.
        event_id: UUID for this event.
        deal_id: Deal identifier (partition key).
        period_start: ISO date (YYYY-MM-DD) for period start.
        period_end: ISO date (YYYY-MM-DD) for period end.
        evaluation_status: Deterministic covenant evaluation result.
        covenants_evaluated: Number of covenants checked.
        breaches_count: Number of covenant breaches detected.
        risk_probability: ML-predicted probability of default (0.0-1.0).
        risk_tier: Categorized risk level based on probability.
        model_version: Version string of the ML model used.
        evaluation_latency_ms: Time spent on deterministic evaluation.
        prediction_latency_ms: Time spent on ML inference.
        processed_at: ISO datetime when processing completed.
    """

    type: PredictionEventType
    event_id: str
    deal_id: str
    period_start: str
    period_end: str
    evaluation_status: EvaluationStatus
    covenants_evaluated: int
    breaches_count: int
    risk_probability: float
    risk_tier: RiskTier
    model_version: str
    evaluation_latency_ms: int
    prediction_latency_ms: int
    processed_at: str


# =============================================================================
# Output Event: AlertEventV1
# =============================================================================


class AlertEventV1(TypedDict):
    """High-severity alert event with Gemini-generated summary.

    Published when risk exceeds threshold (> 0.8) or covenant breach occurs.
    Contains human-readable summary text generated by Gemini.

    Fields:
        type: Event type discriminator.
        event_id: UUID for this event.
        deal_id: Deal identifier (partition key).
        alert_type: Category of alert (breach or high_risk).
        severity: Alert severity level.
        risk_probability: ML-predicted probability that triggered alert.
        gemini_summary: Human-readable 1-sentence summary from Gemini.
        triggered_at: ISO datetime when alert was triggered.
    """

    type: AlertEventType
    event_id: str
    deal_id: str
    alert_type: AlertType
    severity: AlertSeverity
    risk_probability: float
    gemini_summary: str
    triggered_at: str


# =============================================================================
